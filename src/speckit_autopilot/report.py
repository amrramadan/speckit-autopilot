def status_summary(paths: RunPaths) -> str:
    from .state import RunLock, StateStore

    if not paths.state.exists():
        return f"No autopilot run found in {paths.repo} (no {paths.state})."
    st = StateStore(paths.state).load()
    lock = RunLock(paths.lock)
    info = lock.read()
    alive = lock.holder_alive()
    events = EventLog(paths.events).read()
    last = events[-1] if events else {}
    phase_counts = Counter(e.get("phase") for e in events if e.get("event") == "phase_start")
    lines = [
        f"Autopilot {st.issue} — {st.description}",
        f"status: {st.status}{' (process alive, pid ' + str(info.get('pid')) + ')' if alive and info else ''}",
        f"current phase: {st.current_phase} · elapsed {st.elapsed_s / 60:.0f} min",
        f"resets: {len(st.resets)} · back-edges: {len(st.back_edges)} · escalations: {len(st.escalations)}",
        "",
        "phase          status             attempts repairs",
    ]
    for p in PHASES:
        r = st.phases.get(p)
        if r:
            lines.append(f"{p:<14} {r.status:<18} {r.attempts:<8} {r.repairs}")
    if st.halt:
        lines += ["", f"HALT: {st.halt.get('reason')}", f"see {paths.report}"]
    if last:
        lines += ["", f"last event: {last.get('ts')} {last.get('event')} {last.get('phase', '')} {str(last.get('summary', ''))[:160]}"]
    if phase_counts:
        lines += [f"phase entries: {dict(phase_counts)}"]
    return "\n".join(lines)


