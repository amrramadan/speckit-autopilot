def resume_command(state: RunState, python: str | None = None) -> str:
    py = python or sys.executable
    flags = ""
    if state.flags.get("allow_escalations"):
        flags += " --allow-escalations"
    if state.flags.get("until"):
        flags += f" --until {state.flags['until']}"
    return (
        f"{shlex.quote(py)} -m speckit_autopilot --repo {shlex.quote(state.repo)} "
        f"--issue {shlex.quote(state.issue)} {shlex.quote(state.description)} --resume{flags}"
    )


def write_halt_report(
    paths: RunPaths,
    state: RunState,
    *,
    reason: str,
    phase: str | None,
    failed_checks: list[str],
    last_judge: dict[str, Any] | None,
    python: str | None = None,
    priority: str = "normal",
    status: str = "halted",
) -> str:
    """``status`` "stopped" (SIGTERM / SIGINT / --stop) titles the report STOPPED: nothing failed, --resume continues."""
    rec = state.phases.get(phase or "", None)
    lines = [
        f"# Autopilot {'STOPPED' if status == 'stopped' else 'HALTED'} — {state.issue}",
        "",
        f"**Priority:** {priority.upper()}  ",
        f"**Why it stopped:** {reason}  ",
        f"**Phase:** {phase or '—'} · attempt {rec.attempts if rec else 0} · repairs used {rec.repairs if rec else 0}  ",
        f"**When:** {now_iso()} · run `{state.run_id}`  ",
        f"**Branch:** {state.feature_branch or '—'} · feature dir: {state.feature_dir or '—'}  ",
        f"**Elapsed:** {state.elapsed_s / 60:.0f} min",
        "",
        "## Failed checks",
        "",
    ]
    lines += [f"- {c}" for c in failed_checks] or ["- (none recorded)"]
    lines += ["", "## Last judge reasoning", ""]
    if last_judge:
        lines += ["```json", json.dumps(last_judge, indent=2, ensure_ascii=False)[:6000], "```"]
    else:
        lines += ["(no judge call recorded)"]
    lines += ["", "## Escalations", ""]
    lines += [f"- [{e.get('phase')}] {e.get('reason')}" for e in state.escalations] or ["- none"]
    base = baseline_lines(state)
    if base:
        lines += ["", "## Test baseline (failures already on the base branch)", "", *base]
    lines += ["", "## Phase status", "", _phase_table(state), "", "## Resume", "", "Fix the cause above (or accept it), then run:", "", "```bash", resume_command(state, python), "```", ""]
    lines += [
        "To restart at a specific phase instead (its preconditions are re-checked first), replace `--resume` with `--from <phase>`.",
        "",
        f"Event log: `{paths.events}` · transcripts: `{paths.transcripts}/`",
        "",
    ]
    text = redact("\n".join(lines))
    atomic_write(paths.report, text)
    return text


def _phase_table(state: RunState) -> str:
    # no cost column: runs use the Claude subscription, so the SDK's USD figures are API-equivalent, not spend
    rows = ["| Phase | Status | Attempts | Repairs | Duration |", "|---|---|---|---|---|"]
    for p in PHASES:
        r = state.phases.get(p)
        if r is None:
            rows.append(f"| {p} | pending | 0 | 0 | — |")
        else:
            rows.append(f"| {p} | {r.status} | {r.attempts} | {r.repairs} | {r.duration_s / 60:.1f} min |")
    return "\n".join(rows)


def sandbox_text(state: RunState) -> str:
    """One line on the OS sandbox the run used (state.flags["sandbox"], recorded at run start)."""
    s = state.flags.get("sandbox") or {}
    if not s:
        return "—"
    if not s.get("active"):
        return f"{s.get('mode')}: not active ({s.get('detail')})"
    return f"{s.get('mode')}: active ({s.get('detail')}); feature_start, ship and linear run unsandboxed"


def baseline_lines(state: RunState) -> list[str]:
    """Report lines for the test baseline: what the base commit measured, and which pre-existing failures a gate
    tolerated (or why a failure was not tolerated). Empty when no baseline is in play."""
    b = state.flags.get("test_baseline")
    used = state.flags.get("baseline_used") or {}
    refused = state.flags.get("baseline_notes") or {}
    if not b and not used and not refused:
        return []
    out: list[str] = []
    if b:
        sha = str(b.get("sha") or "?")[:12]
        fails = b.get("failures")
        if fails is None:
            out.append(f"- ⚠️ Base `{sha}`: {b.get('note') or 'the failing tests are unknown'}. Every failing test fails the gates (strict).")
        elif not fails:
            out.append(f"- Base `{sha}`: `{b.get('cmd')}` passed there, so no failure is tolerated.")
        else:
            out.append(f"- Base `{sha}`: {len(fails)} test(s) already failing before this feature: " + "; ".join(fails[:15]) + (" …" if len(fails) > 15 else ""))
    out += [f"- Tolerated at {where}: {detail}" for where, detail in used.items()]
    out += [f"- Not tolerated at {where}: {detail}" for where, detail in refused.items()]
    return out


def write_final_report(
    paths: RunPaths,
    state: RunState,
    events: list[dict[str, Any]],
    decisions: list[dict[str, Any]],
    *,
    title: str = "Autopilot COMPLETED",
    human_open: list[str] | None = None,
    pause_items: list[str] | None = None,
    resume: str | None = None,
) -> str:
    """``pause_items`` (with ``resume``) explain what a person must do before ``--resume``; ``human_open`` lists the
    human-only tasks of tasks.md that are still open (None: not known, e.g. before tasks.md exists)."""
    dec = [d for d in decisions if d.get("kind") == "decision"]
    followed = sum(1 for d in dec if d.get("followed_recommendation") is True)
    rejected = sum(1 for d in dec if d.get("followed_recommendation") is False and d.get("recommended"))
    no_rec = sum(1 for d in dec if not d.get("recommended"))
    lines = [
        f"# {title} — {state.issue}",
        "",
        f"{state.description}",
        "",
    ]
    if pause_items:
        lines += ["## What a person must do before resuming", "", *[f"- {x}" for x in pause_items], ""]
        if resume:
            lines += ["Then resume:", "", "```bash", resume, "```", ""]
    lines += [
        f"- Run: `{state.run_id}` · started {state.started_at} · finished {now_iso()}",
        f"- Wall clock: {state.elapsed_s / 60:.1f} min",
        f"- Branch: {state.feature_branch or '—'} → {state.base_branch}",
        f"- PR: {state.ship.get('pr_url') or '—'} · merge commit: {state.ship.get('merge_commit') or '—'} · CI: {state.ship.get('ci') or '—'}",
        (f"- Linear: off ({(state.flags.get('linear') or {}).get('why', 'linear = off')})" if (state.flags.get("linear") or {}).get("enabled") is False
         else f"- Linear: {state.linear.get('summary') or '—'}" + (f" · shared issue ({state.linear['shared']}): status not changed" if state.linear.get("shared") else "")),
        f"- OS sandbox for worker Bash: {sandbox_text(state)}",
        "",
        "## Phases",
        "",
        _phase_table(state),
        "",
        "## Context resets",
        "",
    ]
    lines += [f"- {r.get('ts', '')} [{r.get('phase')}] {r.get('reason')}" for r in state.resets] or ["- none"]
    lines += ["", "## Routing decisions", ""]
    lines += [f"- {b.get('from')} → {b.get('to')}{' (early, before any fix)' if b.get('early') else ''}: {b.get('reason')}" for b in state.back_edges] or ["- none (straight run)"]
    if state.model_switches:
        lines += ["", "## Worker model switches (model_mode = auto)", ""]
        lines += [f"- {m.get('ts', '')} [{m.get('phase')}] {m.get('from') or '(start)'} → {m.get('to')}: {m.get('reason')}" for m in state.model_switches]
    if human_open is not None:
        lines += ["", "## Human-only tasks (tasks.md, for a person)", ""]
        lines += [f"- [ ] {t}" for t in human_open] or ["- none open"]
    base = baseline_lines(state)
    if base:
        lines += ["", "## Test baseline (failures already on the base branch)", "", *base]
    lines += [
        "",
        "## Decisions",
        "",
        f"- Total: {len(dec)} · followed recommendation: {followed} · rejected recommendation: {rejected} · no recommendation offered: {no_rec}",
        f"- High impact: {sum(1 for d in dec if d.get('impact') == 'high')}",
        f"- Escalations: {len(state.escalations)}",
        "",
        "## Links",
        "",
        f"- decisions.md: `{Path(state.feature_dir) / 'decisions.md' if state.feature_dir else '—'}`",
        f"- Event log: `{paths.events}`",
        f"- Transcripts: `{paths.transcripts}/`",
        "",
    ]
    text = redact("\n".join(lines))
    atomic_write(paths.report, text)
    return text


