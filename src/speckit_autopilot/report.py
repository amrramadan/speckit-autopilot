class DecisionLog:
    """Source of truth is ``.autopilot/decisions.jsonl``; ``decisions.md`` is rendered from it.

    ``decisions.md`` lives in the feature directory so cc-ship commits it. It is frozen
    right before ship; anything logged afterwards renders to ``.autopilot/decisions-post-ship.md``
    so the base branch is never left dirty.
    """

    FILENAME = "decisions.md"

    def __init__(self, paths: RunPaths, state: RunState):
        self.paths = paths
        self.state = state

    # -- storage ------------------------------------------------------------------------
    def entries(self) -> list[dict[str, Any]]:
        p = self.paths.decisions_jsonl
        if not p.exists():
            return []
        out = []
        for line in p.read_text(encoding="utf-8").splitlines():
            if line.strip():
                try:
                    out.append(json.loads(line))
                except json.JSONDecodeError:
                    pass
        return out

    def _append(self, rec: dict[str, Any]) -> None:
        self.paths.root.mkdir(parents=True, exist_ok=True)
        rec = {"ts": now_iso(), "post_ship": self.state.decisions_frozen, **rec}
        with self.paths.decisions_jsonl.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(json.loads(redact(json.dumps(rec, ensure_ascii=False))), ensure_ascii=False) + "\n")
        self.sync()

    def add_judge_decisions(self, phase: str, mode: str, decisions: list[dict[str, Any]], attempt: int = 0) -> None:
        for d in decisions or []:
            self._append({"kind": "decision", "phase": phase, "mode": mode, "attempt": attempt, **d})

    def add_routing(self, phase: str, action: str, target: str | None, reason: str, *, applied: bool = True, note: str = "", early: bool = False) -> None:
        """``early``: the round-1 root-cause check of analyze / review (before any fix), not the after-repairs route."""
        rec = {"kind": "routing", "phase": phase, "action": action, "target": target, "reason": reason, "applied": applied, "note": note}
        if early:
            rec["early"] = True
        self._append(rec)

    def add_escalation(self, phase: str, reason: str, item: str = "") -> None:
        self._append({"kind": "escalation", "phase": phase, "reason": reason, "item": item})

    def add_note(self, phase: str, text: str) -> None:
        self._append({"kind": "note", "phase": phase, "text": text})

    def recent(self, n: int = 25) -> list[dict[str, Any]]:
        return [e for e in self.entries() if e.get("kind") in ("decision", "routing", "escalation")][-n:]

    # -- rendering ----------------------------------------------------------------------
    def feature_file(self) -> Path | None:
        return Path(self.state.feature_dir) / self.FILENAME if self.state.feature_dir else None

    def sync(self) -> None:
        entries = self.entries()
        if not self.state.decisions_frozen:
            f = self.feature_file()
            if f is not None and f.parent.is_dir():
                atomic_write(f, render_decisions_md(self.state, [e for e in entries if not e.get("post_ship")]))
        post = [e for e in entries if e.get("post_ship")]
        if post:
            atomic_write(self.paths.post_ship_decisions, render_decisions_md(self.state, post, title="Autopilot decisions after ship (not committed)"))

    def freeze(self) -> Path | None:
        """Final render into the feature dir; later decisions go to .autopilot/ only."""
        self.state.decisions_frozen = False
        self.sync()
        self.state.decisions_frozen = True
        return self.feature_file()


def render_decisions_md(state: RunState, entries: list[dict[str, Any]], title: str = "Autopilot decisions") -> str:
    lines = [
        f"# {title} — {state.issue}",
        "",
        f"Feature: {state.description}  ",
        f"Run: `{state.run_id}` · started {state.started_at}  ",
        "Generated by Spec Kit Autopilot. Every decision below was made by the AI judge, not a human.",
        "",
    ]
    decisions = [e for e in entries if e.get("kind") == "decision"]
    followed = sum(1 for d in decisions if d.get("followed_recommendation") is True)
    rejected = sum(1 for d in decisions if d.get("followed_recommendation") is False and d.get("recommended"))
    high = [d for d in decisions if d.get("impact") == "high"]
    lines += [
        "## Summary",
        "",
        f"- Decisions: {len(decisions)} (followed recommendation: {followed}, rejected recommendation: {rejected})",
        f"- High-impact decisions: {len(high)}",
        f"- Escalations: {sum(1 for e in entries if e.get('kind') == 'escalation')}",
        f"- Routing decisions: {sum(1 for e in entries if e.get('kind') == 'routing')}",
        "",
    ]
    by_phase: dict[str, list[dict[str, Any]]] = {}
    for e in entries:
        by_phase.setdefault(e.get("phase", "?"), []).append(e)
    order = [p for p in PHASES if p in by_phase] + [p for p in by_phase if p not in PHASES]
    for phase in order:
        lines += [f"## {phase}", ""]
        n = 0
        for e in by_phase[phase]:
            kind = e.get("kind")
            if kind == "decision":
                n += 1
                rec = e.get("recommended")
                fr = e.get("followed_recommendation")
                fr_txt = "n/a" if not rec else ("yes" if fr else "**no**")
                lines += [
                    f"### {phase}-{n}: {_one_line(e.get('item', ''))}",
                    "",
                    f"- **Chosen:** {_one_line(e.get('chosen', ''))}",
                    f"- **Recommended:** {_one_line(rec) if rec else '—'} · followed: {fr_txt}",
                    f"- **Impact:** {e.get('impact', '?')} · mode: {e.get('mode', '?')} · {e.get('ts', '')}",
                    f"- **Rationale:** {_one_line(e.get('rationale', ''))}",
                    f"- **Evidence:** {_one_line(e.get('evidence', ''))}",
                    "",
                ]
            elif kind == "routing":
                applied = "" if e.get("applied", True) else " (not applied: " + _one_line(e.get("note", "")) + ")"
                label = "Routing (early, before any fix)" if e.get("early") else "Routing"
                lines += [f"- **{label}:** {e.get('action')} → {e.get('target') or '—'}{applied}: {_one_line(e.get('reason', ''))}", ""]
            elif kind == "escalation":
                lines += [f"- ⚠️ **Escalation:** {_one_line(e.get('reason', ''))} {('(' + _one_line(e.get('item', '')) + ')') if e.get('item') else ''}", ""]
            elif kind == "note":
                lines += [f"- Note: {_one_line(e.get('text', ''))}", ""]
    return "\n".join(lines).rstrip() + "\n"


def _one_line(s: Any) -> str:
    return " ".join(str(s or "").split())


