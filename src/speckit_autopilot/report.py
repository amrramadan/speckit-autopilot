def notify(command_template: str | None, message: str, log: EventLog | None = None) -> None:
    """Run the configured notification command. The message is never interpolated into shell text unquoted:
    ``{message}`` is replaced by a shell-quoted string, and it is also exported as $AUTOPILOT_MESSAGE."""
    if not command_template:
        return
    import os

    msg = " ".join(str(message).split())[:200]
    cmd = command_template.replace("{message}", shlex.quote(msg))
    try:
        subprocess.run(cmd, shell=True, timeout=20, capture_output=True, env={**os.environ, "AUTOPILOT_MESSAGE": msg})
    except Exception as exc:  # pragma: no cover - best effort
        if log:
            log.emit("notify_failed", error=repr(exc))
